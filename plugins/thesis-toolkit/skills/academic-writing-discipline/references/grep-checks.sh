#!/usr/bin/env bash
# grep-checks.sh — 學術中文寫作品質自檢腳本
#
# 用法：把要檢查的稿件另存為純文字/Markdown（例如 檔案.md），
#   bash grep-checks.sh 檔案.md
# 或直接複製各段指令，把「檔案.md」換成你的檔名。
#
# 每組指令附註「應為空」或「需人工判讀」：
#   - 「應為空」：跑出結果代表有問題，逐條修正。
#   - 「需人工判讀」：跑出結果不等於一定有問題，需要人眼區分合理用法與違規用法
#     （例如「影響」的名詞性用法、引用別人實驗時合理使用因果動詞）。
#
# 本腳本只做偵測，不自動修改檔案。

FILE="${1:-檔案.md}"

# 中文字元範圍（[一-龥]）與全形標點要在 UTF-8 locale 下才會逐字比對；
# Windows Git Bash 預設 locale 不是 UTF-8，會變成逐 byte 比對而漏抓或誤抓。
case "${LC_ALL:-${LC_CTYPE:-$LANG}}" in
  *[Uu][Tt][Ff]-8*|*[Uu][Tt][Ff]8*) ;;
  *) export LC_ALL=C.UTF-8 ;;
esac

echo "=== 稽核對象：$FILE ==="

echo ""
echo "--- [因果動詞紀律] 高門檻越線動詞（需人工判讀：區分「引用別人的實驗」與「自己的橫斷面宣稱」） ---"
grep -nE "導致|固化為|促使形成|讓.{0,6}變得|引發|造成" "$FILE"

echo ""
echo "--- [因果動詞紀律] 「影響」（商管慣例可用，不視為錯誤——只人工檢查同一句或同一節內因果與相關語言是否前後一致） ---"
grep -nE "影響" "$FILE"

echo ""
echo "--- [因果動詞紀律] 自創路徑名稱殘留（需人工判讀是否偽裝成既有構念，例如「⟨X⟩侵蝕路徑」「⟨X⟩固化路徑」這類非既有構念的自造詞） ---"
grep -nE "侵蝕路徑|固化路徑|複合惡化" "$FILE"

echo ""
echo "--- [主張強度] 強度詞（需人工判讀：出現時確認有一句原文直接支撐；這是提示，不是錯誤清單） ---"
grep -nE "最強|確實|正是|毫無|取代|核心主張|證實|驗證了|驅動|形塑|大幅|完全中介" "$FILE"

echo ""
echo "--- [主張強度] 全稱句（需人工判讀：加「就本研究回顧的文獻而言」這類限定或刪） ---"
grep -nE "多數研究|大多數研究|每當|往往|普遍認為" "$FILE"

echo ""
echo "--- [構句原則] 歐化：弱動詞＋抽象名詞（需人工判讀能否還原為單純動詞） ---"
grep -nE "進行了?[一-龥]{2}|予以[一-龥]|加以[一-龥]|做出[一-龥]{2}|給予[一-龥]{2}" "$FILE"

echo ""
echo "--- [構句原則] 「存在」濫用（應為空，或改直接陳述） ---"
grep -nE "存在著|問題.{0,4}存在|存在.{0,4}差異|存在.{0,4}關係|存在.{0,4}現象" "$FILE"

echo ""
echo "--- [構句原則] 抽象名詞化主語（需人工判讀能否還原為動作短語） ---"
grep -nE "的進行|的建構|的收集|的形成|的產生|的提出" "$FILE"

echo ""
echo "--- [構句原則] 中間肥大易發句型（需人工判讀中間修飾是否過長） ---"
grep -nE "由於.{15,}因此|對於.{10,}的問題|在.{15,}的情況" "$FILE"

echo ""
echo "--- [台灣學術用語] 大陸用語 / 地區用語混用（應為空） ---"
grep -nE "被試|數據收集|信息|回歸分析|結果表明|顯著性水平|通過問卷|人工智能|編程|用戶|反饋|視頻|質量|算法|數據庫|優化|場景|獲取|給出|打造|賦能|落地|抓手|助力|受眾|默認|擬合|聚合效度|橫截面|縱向|方差|置信區間" "$FILE"

echo ""
echo "--- [APA 7] 引用「等」後缺「人」（應為空） ---"
grep -nE "等[，,;；)]" "$FILE"

echo ""
echo "--- [APA 7] 全形破折號用於頁碼（應改半形 en dash –） ---"
grep -nE "[0-9]+—[0-9]+" "$FILE"

echo ""
echo "--- [連接詞與標點] 破折號插說（應為空，專有名詞除外） ---"
grep -nE "—" "$FILE"

echo ""
echo "--- [連接詞與標點] 半形標點誤用於中文行文（應為空） ---"
grep -nE '[^A-Za-z0-9]"[^"]*"[^A-Za-z0-9]|,|;' "$FILE"

echo ""
echo "--- [去 AI 感] AI 套話 / 空泛結語（應為空） ---"
grep -onE "換句話說|換言之|綜上所述|前所未有|具有重要意涵|填補研究缺口|奠定.{0,4}基礎|開啟.{0,4}可能" "$FILE"

echo ""
echo "--- [去 AI 感] 「值得注意的是」出現次數（每份檔案應 ≤2） ---"
grep -o "值得注意的是" "$FILE" | wc -l

echo ""
echo "--- [去 AI 感] 「首先/其次/第一/第二」連用列舉（需人工判讀是否連用超過三段） ---"
grep -nE "首先|其次|再者|最後|第一，|第二，|第三，|其一|其二|其三" "$FILE"

echo ""
echo "--- [去 AI 感] 「不是X而是Y」句型計數（每份檔案應 ≤1） ---"
grep -cE "而非|取而代之|不[^，。]{0,8}而是|固然.{0,15}真正|與其.{0,10}不如" "$FILE"

echo ""
echo "--- [去 AI 感] 過度 hedging 連疊（需人工判讀是否四連疊） ---"
grep -nE "可能.{0,4}或許.{0,4}大概|或許.{0,4}也許" "$FILE"

echo ""
echo "--- [去 AI 感] 流水帳式「Author (Year) 指出」開頭（需人工判讀是否連續三段以上） ---"
grep -nE "^[A-Za-z一-龥]+(（|\()[0-9]{4}(）|\))(指出|發現|提出|認為)" "$FILE"

echo ""
echo "--- [去 AI 感] 句中冒號（需人工判讀：列舉、定義、引用前的冒號照用；引出解釋或結論的改成完整句） ---"
grep -nE "[一-龥]：[一-龥「]" "$FILE"

echo ""
echo "--- [APA 7] 同一句敘述引用後又加括號引用（需人工判讀：括號裡是同一篇就刪） ---"
grep -nE "[（(][0-9]{4}[a-z]?[）)][^。]*[（(][^（）()]*[,，] ?[0-9]{4}[a-z]?[）)]" "$FILE"

echo ""
echo "--- [連接詞] 「因」開頭的句子（需人工判讀：後面要有結果） ---"
grep -nE "(^|。)因[^此為而應]" "$FILE"

echo ""
echo "--- [文獻回顧] 他人研究的統計數字（需人工判讀：文獻回顧章轉述別人的研究時，寫方向與顯著與否即可） ---"
grep -nE "β ?=|p ?[<=＜]|[Nn] ?=" "$FILE"

echo ""
echo "=== 稽核完畢 ==="
echo "「需人工判讀」的項目請對照 references/sentence-and-causal.md、references/taiwan-usage-apa.md、"
echo "references/ai-flavor-and-common-errors.md 逐條確認是否真的違規。"
